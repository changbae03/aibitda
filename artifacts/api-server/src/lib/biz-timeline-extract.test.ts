import { describe, it, expect } from "vitest";
import { extractSections } from "./biz-timeline-extract";

/**
 * DART 사업보고서의 htmlToText 통과 후 모양을 최소로 재현한 픽스처.
 *
 * 핵심은 **목차와 본문에 같은 머리글이 두 번** 나온다는 것 — 목차 항목들은 서로
 * 바짝 붙어 있고, 본문은 다음 대분류(III.)까지 멀리 벌어진다. 옛 코드는 이 구분을
 * 못 해서 "사업의 개요" 첫 매치(=목차)를 잡고 근처만 떴다.
 *
 * 아래 픽스처는 세 회귀를 동시에 건다:
 *  - 목차가 아니라 본문을 잡는가
 *  - "85%"·"70%" 같은 짧은 숫자 셀을 지우지 않는가 (옛 length>3 필터가 죽였다)
 *  - 위험관리 보일러플레이트를 버리는가
 *  - 문서 깊숙이 묻힌 시장점유율을 살려내는가
 */
function makeReport(): string {
  // 목차 — 머리글이 바짝 붙어 있다
  const toc = [
    "II. 사업의 내용",
    "1. 사업의 개요",
    "2. 주요 제품 및 서비스",
    "3. 원재료 및 생산설비",
    "4. 매출 및 수주상황",
    "5. 위험관리 및 파생거래",
    "6. 주요계약 및 연구개발활동",
    "7. 기타 참고사항",
    "III. 재무에 관한 사항",
  ];
  // 본문 — 다음 III.까지 멀리 벌어진다.
  // 소분류마다 실제 보고서처럼 서술 + 표를 넣어 "빈 섹션 버리기"(100자) 문턱을 넘긴다.
  const pad = (s: string) => s + " " + "설명문장을덧붙여실제보고서분량을맞춘다".repeat(4);
  const body = [
    "II. 사업의 내용",
    "1. 사업의 개요",
    pad("당사는 반도체를 생산하는 회사입니다."),
    "2. 주요 제품 및 서비스",
    pad("주력 제품은 DRAM 입니다."),
    "매출 비중",
    "70%",
    "3. 원재료 및 생산설비",
    pad("생산설비 현황은 다음과 같습니다."),
    "가동률",
    "85%",
    "생산능력",
    "41,216,512",
    "4. 매출 및 수주상황",
    pad("매출 및 수주 상황은 다음과 같습니다."),
    "수주잔고",
    "1,234",
    "5. 위험관리 및 파생거래",
    pad("환리스크관리정책보일러플레이트문구입니다이런건연도비교에값이없습니다"),
    "6. 주요계약 및 연구개발활동",
    pad("연구개발 활동 내역은 다음과 같습니다."),
    "연구개발비용 합계",
    "6,732,527",
    "7. 기타 참고사항",
  ];
  // 기타참고를 상한 넘게 채워 점유율을 깊숙이 민다
  const filler = Array.from({ length: 40 }, (_, i) => `가나다라마바사업계현황설명문장 ${i}`);
  const tail = ["시장점유율", "DRAM 1위", "III. 재무에 관한 사항"];
  return [...toc, ...body, ...filler, ...tail].join("\n");
}

describe("extractSections — 본문을 잡고 데이터를 살린다", () => {
  // base를 작게 줘 기타참고가 상한을 넘도록 만든다(트림 경로 검증)
  const out = extractSections(makeReport(), 200);

  it("목차가 아니라 본문을 잡는다", () => {
    // 본문에만 있는 실제 서술이 담겨야 한다
    expect(out).toContain("당사는 반도체를 생산하는 회사");
  });

  it("짧은 숫자 셀(70%·85%)을 지우지 않는다", () => {
    // 옛 length>3 필터는 3글자 "85%"를 통째로 버렸다
    expect(out).toContain("85%");
    expect(out).toContain("70%");
  });

  it("위험관리(파생거래) 보일러플레이트는 버린다", () => {
    expect(out).not.toContain("환리스크관리정책보일러플레이트");
  });

  it("깊숙이 묻힌 시장점유율을 트림이 살려낸다", () => {
    // 상한을 넘겨 앞부분만 남기면 잘렸을 값을, 신호 트림이 끌어온다
    expect(out).toContain("시장점유율");
  });

  it("소분류 이름표를 단다 — 기간끼리 대조하기 위해", () => {
    expect(out).toContain("### [매출수주]");
    expect(out).toContain("### [기타참고]");
  });
});
